#!/usr/bin/env node
/* ═══════════════════════════════════════════════════════════════════════════
   ops-archive-index.mjs — WHAT WAS CUT OUT OF THE GROUND STATE, AND FROM WHERE

   `docs/canonical/OPERATIONS.md` is cut to a ground state that can be read
   whole; the material it shed lives in `OPERATIONS_ARCHIVE/`. This writes the
   one table that says which file holds which section.

   IT RUNS ON DEMAND AND NEVER ON A TIMER. No relative-age labels, no "last
   written" stamp, no time-derived value of ANY kind: a generated file that
   changes when nothing changed is churn that sweeps itself into whatever
   commit it touches, which is exactly why `npm run desk` is unsafe to include
   in one. Run this twice with no edits between and the second run must write
   byte-identical output.

   The SOURCE SECTION is read out of each file's own provenance pointer — its
   first line — rather than held in a table here, so there is one place to
   correct and it is the file itself.

   Run as `npm run ops:archive`.
   ═══════════════════════════════════════════════════════════════════════════ */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO   = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const REL    = "docs/canonical/OPERATIONS_ARCHIVE";
const DIR    = path.join(REPO, REL);
const INDEX  = "INDEX.md";
const GROUND = "docs/canonical/OPERATIONS.md";

if (!fs.existsSync(DIR)) {
  console.error(`FAIL — ${REL} does not exist.`);
  process.exit(1);
}

/* Sorted by name so the output does not depend on directory order, which is
   filesystem-dependent and would churn across machines. INDEX.md excludes
   itself: a file cannot carry its own byte count. */
const files = fs.readdirSync(DIR)
  .filter(f => f.endsWith(".md") && f !== INDEX)
  .sort();

const rows = files.map(f => {
  const full = path.join(DIR, f);
  const bytes = fs.statSync(full).size;
  /* The provenance pointer is line 1 and reads:
       > Cut from `docs/canonical/OPERATIONS.md` <section>, at HEAD `<sha>`.
     Take what sits between the source path and the HEAD clause. */
  const first = fs.readFileSync(full, "utf8").split("\n")[0];
  const m = /`docs\/canonical\/OPERATIONS\.md`\s*(.*?),?\s*at HEAD `([0-9a-f]+)`/.exec(first);
  const source = m ? (m[1].replace(/^—\s*/, "").replace(/\s*—$/, "").trim() || "(unnamed)") : "(no provenance pointer)";
  const head   = m ? m[2] : "(none)";
  return { f, bytes, source, head };
});

const total = rows.reduce((s, r) => s + r.bytes, 0);
const ground = fs.statSync(path.join(REPO, GROUND)).size;

const out = [
  "# OPERATIONS_ARCHIVE — index",
  "",
  "Generated by `npm run ops:archive`. Do not edit by hand; the next run",
  "overwrites it. Every row's source section is read from that file's own",
  "provenance pointer, so a correction goes in the file, not here.",
  "",
  "| file | bytes | cut from | at HEAD |",
  "|---|---:|---|---|",
  ...rows.map(r => `| \`${r.f}\` | ${r.bytes.toLocaleString("en-US")} | ${r.source} | \`${r.head}\` |`),
  `| **total** | **${total.toLocaleString("en-US")}** | | |`,
  "",
  `The ground state \`${GROUND}\` holds ${ground.toLocaleString("en-US")} bytes.`,
  "It keeps every archived section's heading and a pointer to the file below,",
  "so the section inventory is readable without opening any of them.",
  "",
];

fs.writeFileSync(path.join(DIR, INDEX), out.join("\n"), "utf8");

console.log("");
console.log(`  ${REL}/${INDEX} written — ${rows.length} archive file(s), ${total.toLocaleString("en-US")} bytes.`);
for (const r of rows) console.log(`    ${r.f.padEnd(26)} ${String(r.bytes).padStart(8)}  ${r.source}`);
console.log("");
